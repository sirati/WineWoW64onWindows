#!/usr/bin/env python3
"""Bundle a clean, frozen checkout's test inputs, runners and PE outputs."""
import hashlib
import argparse
import json
from pathlib import Path
import subprocess
import zipfile

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--out-directory', type=Path, default=root / 'prototype/out')
parser.add_argument('--upstream-directory', type=Path)
parser.add_argument('--corpus-directory', type=Path, default=root / 'prototype/unmodified')
parser.add_argument('--evidence-directory', type=Path, default=root / 'evidence')
options = parser.parse_args()
def git(*args):
    return subprocess.check_output(['git', '-C', str(root), *args], text=True).strip()

assert not git('status', '--porcelain'), 'Use a clean frozen worktree, not a working build.'
# Build outputs are generated by Nix and deliberately absent from Git.
def collect(directory, prefix, suffixes):
    return [(p, prefix / p.relative_to(directory)) for p in sorted(directory.rglob('*'))
            if p.is_file() and p.suffix.lower() in suffixes and 'results' not in p.parts]
paths = collect(options.out_directory, Path('out'), ('.exe', '.dll', '.nls', '.txt'))
paths += [(root / name, Path(name).relative_to('prototype'))
          for name in git('ls-files', '--', 'prototype/*.ps1').splitlines()]
upstream_manifest = options.out_directory / 'upstream-tests/manifest.json'
if upstream_manifest.is_file():
    paths.append((upstream_manifest, Path('out/upstream-tests/manifest.json')))
if options.upstream_directory:
    paths += collect(options.upstream_directory, Path('out/upstream-tests'), ('.exe', '.dll', '.json', '.txt'))
paths += collect(options.corpus_directory, Path('unmodified'), ('.exe', '.dll', '.txt', '.json'))
assert len(paths) == len({name for _, name in paths}), 'Duplicate bundle paths'
assert (options.out_directory / 'wine-host.exe').is_file(), 'Select the Nix tests output directory.'
manifest = {'commit': git('rev-parse', 'HEAD'), 'files': [
    {'path': name.as_posix(), 'sha256': hashlib.sha256(path.read_bytes()).hexdigest().upper()}
    for path, name in paths]}
evidence = options.evidence_directory
evidence.mkdir(exist_ok=True, parents=True)
(evidence / 'candidate-files.json').write_text(json.dumps(manifest, indent=2) + '\n')
verify = r'''param([string]$Root=$PSScriptRoot)
$ErrorActionPreference='Stop'
$manifest=Get-Content -Raw "$Root/candidate-files.json"|ConvertFrom-Json
foreach($row in $manifest.files) {
    $actual=(Get-FileHash -Algorithm SHA256 -LiteralPath (Join-Path $Root $row.path)).Hash
    if($actual -ne $row.sha256){throw "Candidate hash mismatch: $($row.path)"}
}
Write-Output "VERIFIED_CANDIDATE=$($manifest.commit) FILES=$($manifest.files.Count)"
'''
with zipfile.ZipFile(evidence / 'vm-test-bundle.zip', 'w', zipfile.ZIP_DEFLATED, compresslevel=6) as bundle:
    for path, name in paths:
        bundle.write(path, name.as_posix())
    bundle.writestr('candidate-files.json', json.dumps(manifest, indent=2) + '\n')
    bundle.writestr('verify-candidate.ps1', verify)
print(json.dumps({'commit': manifest['commit'], 'files': len(paths),
      'hostSHA256': hashlib.sha256((options.out_directory / 'wine-host.exe').read_bytes()).hexdigest().upper()}, indent=2))
